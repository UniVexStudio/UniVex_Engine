#!/usr/bin/env bash
# Copyright (c) 2026 UniVex Studios. All Rights Reserved.
#
# Builds a self-contained, headless desktop-GL + Vulkan toolchain into $UVE_TOOLCHAIN
# (default ~/toolchain) on a Linux box that has NO package manager access and NO display -
# only gcc/g++/make, python3 + pip, and outbound HTTPS to github.com (codeload), pypi.org and
# registry.npmjs.org. That is exactly the Arena/E2B sandbox this engine is developed in, where
# apt is blocked and GitHub *release assets* (release-assets.githubusercontent.com) are blocked
# too, so everything below comes from git tag tarballs, PyPI wheels or npm tarballs.
#
# What it produces (all under the prefix, nothing touches /usr):
#   bin/m4                      GNU m4 1.4.18 - bison/flex need it at runtime (built from the
#                               tar-mirror/gnu-m4 release import, since ftp.gnu.org is blocked)
#   lib/libOSMesa.so.8          Mesa 25.0.7 off-screen renderer, gallium softpipe, OpenGL 3.3
#                               Core (25.0 is the last Mesa with OSMesa; 25.1 removed it)
#   lib/libGL.so -> libOSMesa   OSMesa exports the full desktop-GL ABI, so CMake's FindOpenGL
#                               and the linker are satisfied without GLX/X11
#   lib/libglfw.so.3            GLFW 3.4, Null platform only (no X11/Wayland), one-line patch so
#                               GLFW_ANY_PLATFORM auto-selects Null; contexts come from OSMesa
#   lib/libGLEW.so              GLEW 2.2 (Perlmint/glew-cmake, pre-generated sources) built in
#                               GLEW_OSMESA mode so glewInit() resolves through OSMesa
#   vulkan/                     SwiftShader Vulkan 1.3 CPU ICD + loader, lifted out of the
#                               @sparticuz/chromium npm tarball (it is Chromium's bundled copy)
#   ~/.univex_env               PATH / M4 / CMAKE_PREFIX_PATH / LD_LIBRARY_PATH / VK_ICD_FILENAMES,
#                               C_INCLUDE_PATH / CPLUS_INCLUDE_PATH / LIBRARY_PATH (tests that
#                               include <GL/gl.h> and <GLFW/glfw3.h> directly expect a system
#                               install) and MESA_GL_VERSION_OVERRIDE=4.6 / MESA_GLSL_VERSION_OVERRIDE=460
#                               (softpipe is really GL 3.3; WindowDescUVE asks for a 4.6 Core context)
#
# Afterwards the engine configures with UVE_HAS_DESKTOP_GL=ON and every GL-gated target
# (uve_rhi_opengl, the GLFW WindowManagerUVE, the editor viewport) compiles AND runs headless.
# FindOpenGL has to run in LEGACY mode: there is no GLVND libOpenGL/libGLX, only libGL -> OSMesa.
#   source ~/.univex_env
#   cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Debug -DUVE_BUILD_TESTS=ON \
#         -DCMAKE_PREFIX_PATH="$HOME/toolchain" -DOpenGL_GL_PREFERENCE=LEGACY \
#         -DOPENGL_INCLUDE_DIR="$HOME/toolchain/include" -DOPENGL_gl_LIBRARY="$HOME/toolchain/lib/libGL.so"
#   cmake --build build -j2 && ctest --test-dir build --output-on-failure -j2
#
# Idempotent: every step checks its install artefact and skips when present. Re-run freely.
# Sizes: ~550 MB of sources downloaded (deleted at the end unless UVE_KEEP_SRC=1), ~45 min on
# 2 vCPUs, almost all of it Mesa.

set -euo pipefail

UVE_TOOLCHAIN="${UVE_TOOLCHAIN:-$HOME/toolchain}"
SRC="$UVE_TOOLCHAIN/src"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"   # for the companion .c files next to this script
JOBS="${JOBS:-$(nproc)}"
MESA_TAG="${MESA_TAG:-mesa-25.0.7}"           # last release with OSMesa
MESA_MIRROR="${MESA_MIRROR:-sailfishos-mirror/mesa}"  # full-tag daily mirror of gitlab.freedesktop.org/mesa/mesa
GLFW_TAG="3.4"
GLEW_TAG="glew-cmake-2.3.1"
ZLIB_TAG="v1.3.1"
EXPAT_TAG="R_2_6_4"
M4_TAG="v1.4.18"
CHROMIUM_NPM_VERSION="${CHROMIUM_NPM_VERSION:-153.0.0}"

log()  { printf '\n\033[1;36m== %s\033[0m\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }

# codeload tag tarball -> $SRC/<name>, stripped of the top-level directory.
fetch() { # name owner/repo tag
    local name="$1" repo="$2" tag="$3"
    [ -d "$SRC/$name" ] && return 0
    log "download $repo @ $tag"
    mkdir -p "$SRC/$name"
    curl -fsSL --retry 3 "https://codeload.github.com/$repo/tar.gz/refs/tags/$tag" \
        | tar xz -C "$SRC/$name" --strip-components=1
}

mkdir -p "$UVE_TOOLCHAIN/bin" "$UVE_TOOLCHAIN/lib" "$SRC"

# ---------------------------------------------------------------------------------------------
# 0. Environment file. Written first so every later step (and every later shell) sees it.
# ---------------------------------------------------------------------------------------------
cat > "$HOME/.univex_env" <<EOF
# Generated by Engine/Tools/headless_gl_toolchain.sh - source this before configuring the engine.
export UVE_TOOLCHAIN="$UVE_TOOLCHAIN"
export PATH="\$UVE_TOOLCHAIN/bin:\$HOME/.local/bin:\$PATH"
export M4="\$UVE_TOOLCHAIN/bin/m4"                       # bison-bin/flex-bin are built with /usr/bin/m4 baked in
export PKG_CONFIG="\$HOME/.local/bin/pkgconf"
export PKG_CONFIG_PATH="\$UVE_TOOLCHAIN/lib/pkgconfig:\$UVE_TOOLCHAIN/share/pkgconfig"
export CMAKE_PREFIX_PATH="\$UVE_TOOLCHAIN"
# The tree assumes GL/GLFW headers and libs sit on the compiler's *default* search path (as a
# distro install would). Emulate that for the private prefix: *_INCLUDE_PATH is -isystem semantics
# (keeps -Werror quiet for third-party headers), LIBRARY_PATH is the link-time counterpart.
export C_INCLUDE_PATH="\$UVE_TOOLCHAIN/include\${C_INCLUDE_PATH:+:\$C_INCLUDE_PATH}"
export CPLUS_INCLUDE_PATH="\$UVE_TOOLCHAIN/include\${CPLUS_INCLUDE_PATH:+:\$CPLUS_INCLUDE_PATH}"
export LIBRARY_PATH="\$UVE_TOOLCHAIN/lib\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
export LD_LIBRARY_PATH="\$UVE_TOOLCHAIN/vulkan:\$UVE_TOOLCHAIN/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
# CPU Vulkan device (SwiftShader). Both spellings: VK_ICD_FILENAMES is the legacy name.
export VK_ICD_FILENAMES="\$UVE_TOOLCHAIN/vulkan/vk_swiftshader_icd.json"
export VK_DRIVER_FILES="\$UVE_TOOLCHAIN/vulkan/vk_swiftshader_icd.json"
# softpipe (no LLVM, no tessellation) tops out at OpenGL 3.3 Core, but WindowDescUVE defaults to
# a 4.6 Core request, which OSMesa would refuse. Mesa's own overrides make it advertise 4.6 / GLSL
# 4.60 instead; compute, SSBO, image load/store and indirect draw are genuinely there, tessellation
# and a few 4.x extras (texture_barrier, shader_draw_parameters, polygon_offset_clamp) are not.
export MESA_GL_VERSION_OVERRIDE=4.6
export MESA_GLSL_VERSION_OVERRIDE=460
EOF
# shellcheck disable=SC1090
source "$HOME/.univex_env"
for rc in "$HOME/.bashrc" "$HOME/.profile"; do
    grep -q 'univex_env' "$rc" 2>/dev/null || echo 'source ~/.univex_env' >> "$rc"
done

# ---------------------------------------------------------------------------------------------
# 1. PyPI: build tools that Debian would normally supply. All are prebuilt manylinux wheels.
#    bison-bin / flex-bin are GNU Bison 3.8.2 / flex 2.6.4 wrapped as wheels (trim21/bison-py).
# ---------------------------------------------------------------------------------------------
log "pip: cmake ninja meson mako pyyaml ply packaging bison-bin flex-bin pkgconf brotli"
python3 -m pip install --user --quiet --disable-pip-version-check --break-system-packages \
    cmake ninja meson mako pyyaml ply packaging bison-bin flex-bin pkgconf brotli
hash -r

# ---------------------------------------------------------------------------------------------
# 2. GNU m4 - bison and flex exec it at runtime. ftp.gnu.org is unreachable; tar-mirror/gnu-m4
#    is a git import of the release tarballs (configure already generated), so no autotools.
# ---------------------------------------------------------------------------------------------
if [ ! -x "$UVE_TOOLCHAIN/bin/m4" ]; then
    fetch m4 tar-mirror/gnu-m4 "$M4_TAG"
    log "build GNU m4 1.4.18"
    (
        cd "$SRC/m4"
        # Two well-known 1.4.18-on-modern-glibc fixes:
        #  - gnulib fflush/fseeko used glibc's private _IO_ftrylockfile (gone in glibc 2.28)
        #  - SIGSTKSZ is sysconf() since glibc 2.34, no longer a preprocessor constant
        sed -i 's/IO_ftrylockfile/IO_EOF_SEEN/' lib/*.c
        grep -q '_IO_IN_BACKUP' lib/stdio-impl.h || echo '#define _IO_IN_BACKUP 0x100' >> lib/stdio-impl.h
        grep -q 'glibc>=2.34' lib/c-stack.c || python3 - <<'PY'
p = 'lib/c-stack.c'; s = open(p).read()
i = s.index('#ifndef SIGSTKSZ')
s = s[:i] + '/* glibc>=2.34: SIGSTKSZ is sysconf(), not a constant */\n#undef SIGSTKSZ\n#define SIGSTKSZ 65536\n' + s[i:]
open(p, 'w').write(s)
PY
        # The git import gives every file the same mtime; make the generated files look fresh
        # so make never tries to re-run autoconf/automake/autoheader (which we do not have).
        touch aclocal.m4; sleep 1; touch configure config.h.in lib/config.hin
        find . -name Makefile.in -exec touch {} +
        ./configure --prefix="$UVE_TOOLCHAIN" --disable-dependency-tracking >configure.log 2>&1
        make -j"$JOBS" AUTOHEADER=true AUTOCONF=true AUTOMAKE=true ACLOCAL=true >make.log 2>&1
        make install AUTOHEADER=true AUTOCONF=true AUTOMAKE=true ACLOCAL=true >install.log 2>&1
    )
fi
"$UVE_TOOLCHAIN/bin/m4" --version | head -1
bison --version | head -1
flex --version

# ---------------------------------------------------------------------------------------------
# 3. zlib + expat: Mesa's two hard library dependencies. expat's git tree carries CMake files.
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/lib/pkgconfig/zlib.pc" ]; then
    fetch zlib madler/zlib "$ZLIB_TAG"
    log "build zlib"
    ( cd "$SRC/zlib" && ./configure --prefix="$UVE_TOOLCHAIN" >configure.log 2>&1 \
        && make -j"$JOBS" >make.log 2>&1 && make install >install.log 2>&1 )
fi
if [ ! -f "$UVE_TOOLCHAIN/lib/pkgconfig/expat.pc" ]; then
    fetch expat libexpat/libexpat "$EXPAT_TAG"
    log "build expat"
    cmake -S "$SRC/expat/expat" -B "$SRC/expat/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_INSTALL_PREFIX="$UVE_TOOLCHAIN" -DEXPAT_BUILD_TESTS=OFF -DEXPAT_BUILD_EXAMPLES=OFF \
        -DEXPAT_BUILD_TOOLS=OFF -DEXPAT_BUILD_DOCS=OFF -DEXPAT_SHARED_LIBS=ON >/dev/null
    cmake --build "$SRC/expat/build" -j"$JOBS" >/dev/null
    cmake --install "$SRC/expat/build" >/dev/null
fi

# ---------------------------------------------------------------------------------------------
# 4. Mesa: OSMesa + softpipe only. No X11, no Wayland, no DRM, no LLVM (llvmpipe would be much
#    faster but needs LLVM dev libraries, which nothing on PyPI/npm provides).
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/lib/libOSMesa.so.8" ]; then
    fetch mesa "$MESA_MIRROR" "$MESA_TAG"
    log "configure Mesa $MESA_TAG (OSMesa, softpipe)"
    meson setup "$SRC/mesa/build" "$SRC/mesa" \
        --prefix="$UVE_TOOLCHAIN" --libdir=lib --buildtype=release -Db_ndebug=true \
        -Dplatforms= -Dglx=disabled -Degl=disabled -Dgbm=disabled \
        -Dosmesa=true -Dgallium-drivers=softpipe -Dvulkan-drivers= \
        -Dllvm=disabled -Dshared-llvm=disabled \
        -Dopengl=true -Dgles1=disabled -Dgles2=disabled -Dshared-glapi=enabled \
        -Dzstd=disabled -Dlibunwind=disabled -Dvalgrind=disabled -Dlmsensors=disabled \
        -Dgallium-vdpau=disabled -Dgallium-va=disabled -Dgallium-xa=disabled \
        -Dgallium-nine=false -Dgallium-rusticl=false -Dvideo-codecs= -Dtools= \
        -Dbuild-tests=false -Dmicrosoft-clc=disabled -Dintel-rt=disabled >"$SRC/mesa-setup.log" 2>&1
    log "build Mesa (this is the long one)"
    ninja -C "$SRC/mesa/build" -j"$JOBS" >"$SRC/mesa-build.log" 2>&1
    ninja -C "$SRC/mesa/build" install >"$SRC/mesa-install.log" 2>&1
fi
# FindOpenGL (legacy path) wants libGL.so + GL/gl.h. OSMesa *is* a complete libGL minus GLX -
# and that "minus GLX" matters: generic GL loaders (Dear ImGui's imgl3w in the editor, glad's
# default Linux path, ...) dlopen("libGL.so.1") and refuse to work unless glXGetProcAddressARB()
# exists. So libGL.so.1 is a 2-function shim forwarding to OSMesaGetProcAddress() with
# libOSMesa.so.8 as DT_NEEDED, and libGL.so (the link-time name) is a GNU ld script that pulls
# in both. Without the shim uve_editor's ImGui UI silently never initialises.
if ! nm -D --defined-only "$UVE_TOOLCHAIN/lib/libGL.so.1" 2>/dev/null | grep -q glXGetProcAddressARB; then
    log "install libGL.so.1 GLX shim over OSMesa"
    mkdir -p "$SRC"
    rm -f "$UVE_TOOLCHAIN/lib/libGL.so.1" "$UVE_TOOLCHAIN/lib/libGL.so"   # may be symlinks to libOSMesa
    cat > "$SRC/libgl_glx_shim.c" <<'C'
#include <GL/osmesa.h>
typedef void (*GLXFunction)(void);
GLXFunction glXGetProcAddressARB(const unsigned char* name) {
    return (GLXFunction) OSMesaGetProcAddress((const char*) name);
}
GLXFunction glXGetProcAddress(const unsigned char* name) { return glXGetProcAddressARB(name); }
C
    gcc -shared -fPIC -O2 -Wl,-soname,libGL.so.1 -I"$UVE_TOOLCHAIN/include" \
        -o "$UVE_TOOLCHAIN/lib/libGL.so.1" "$SRC/libgl_glx_shim.c" -L"$UVE_TOOLCHAIN/lib" -lOSMesa
    printf '/* GNU ld script - headless toolchain: -lGL = GLX shim (libGL.so.1) + OSMesa */\nGROUP ( %s/libGL.so.1 %s/libOSMesa.so.8 )\n' \
        "$UVE_TOOLCHAIN/lib" "$UVE_TOOLCHAIN/lib" > "$UVE_TOOLCHAIN/lib/libGL.so"
fi

# ---------------------------------------------------------------------------------------------
# 5. GLFW 3.4, Null platform only. Upstream refuses to auto-select Null under GLFW_ANY_PLATFORM
#    ("This binary only supports the Null platform"); the engine's WindowManagerUVE calls plain
#    glfwInit(), so make that case connect Null instead. Null + the default (native) context API
#    creates contexts through OSMesa (dlopen libOSMesa.so.8 - hence LD_LIBRARY_PATH above).
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/lib/cmake/glfw3/glfw3Config.cmake" ]; then
    fetch glfw glfw/glfw "$GLFW_TAG"
    log "patch + build GLFW $GLFW_TAG (Null platform, OSMesa contexts)"
    python3 - "$SRC/glfw/src/platform.c" <<'PY'
import sys; p = sys.argv[1]; s = open(p).read()
old = '''    else if (count == 0)
    {
        _glfwInputError(GLFW_PLATFORM_UNAVAILABLE, "This binary only supports the Null platform");
        return GLFW_FALSE;
    }'''
new = '''    else if (count == 0)
    {
        // [UniVex headless toolchain] Built with only the Null platform (no X11/Wayland):
        // let GLFW_ANY_PLATFORM select it, so plain glfwInit() works. Contexts come from OSMesa.
        return _glfwConnectNull(desiredID, platform);
    }'''
if old in s: open(p, 'w').write(s.replace(old, new))
PY
    cmake -S "$SRC/glfw" -B "$SRC/glfw/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_INSTALL_PREFIX="$UVE_TOOLCHAIN" -DBUILD_SHARED_LIBS=ON \
        -DGLFW_BUILD_X11=OFF -DGLFW_BUILD_WAYLAND=OFF \
        -DGLFW_BUILD_EXAMPLES=OFF -DGLFW_BUILD_TESTS=OFF -DGLFW_BUILD_DOCS=OFF >/dev/null
    cmake --build "$SRC/glfw/build" -j"$JOBS" >/dev/null
    cmake --install "$SRC/glfw/build" >/dev/null
fi

# ---------------------------------------------------------------------------------------------
# 6. GLEW for the editor viewport. nigels-com/glew's git tree has no generated glew.c, so use
#    Perlmint/glew-cmake (pre-generated). GLEW_OSMESA makes glewInit() use OSMesaGetProcAddress
#    instead of glXGetProcAddressARB; its CMake still insists on GLVND+GLX on Linux, so skip
#    that check in OSMesa mode.
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/lib/libGLEW.so" ]; then
    fetch glew Perlmint/glew-cmake "$GLEW_TAG"
    log "patch + build GLEW (OSMesa mode)"
    sed -i 's/^if(NOT (WIN32 OR APPLE))$/if(NOT (WIN32 OR APPLE) AND NOT GLEW_OSMESA)/' "$SRC/glew/CMakeLists.txt"
    cmake -S "$SRC/glew" -B "$SRC/glew/build" -G Ninja -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_INSTALL_PREFIX="$UVE_TOOLCHAIN" -DCMAKE_PREFIX_PATH="$UVE_TOOLCHAIN" \
        -DGLEW_OSMESA=ON -DONLY_LIBS=ON -Dglew-cmake_BUILD_STATIC=OFF \
        -DOSMESA_LIBRARY="$UVE_TOOLCHAIN/lib/libOSMesa.so" -DOpenGL_GL_PREFERENCE=LEGACY \
        -DOPENGL_INCLUDE_DIR="$UVE_TOOLCHAIN/include" -DOPENGL_gl_LIBRARY="$UVE_TOOLCHAIN/lib/libGL.so" >/dev/null
    cmake --build "$SRC/glew/build" -j"$JOBS" >/dev/null
    cmake --install "$SRC/glew/build" >/dev/null
fi
# glew.h #includes <GL/glu.h> unless GLEW_NO_GLU is defined by every consumer. Nothing in the
# tree calls glu*, so the header alone (SGI Free B, from the Mesa GLU mirror) is enough - no
# libGLU. Fetched through the GitHub contents API because raw.githubusercontent.com is blocked.
if [ ! -f "$UVE_TOOLCHAIN/include/GL/glu.h" ]; then
    log "install GL/glu.h header (GLEW include dependency)"
    curl -fsSL --retry 3 -H 'Accept: application/vnd.github.raw' \
        "https://api.github.com/repos/Distrotech/glu/contents/include/GL/glu.h" \
        -o "$UVE_TOOLCHAIN/include/GL/glu.h"
    grep -q 'SGI FREE SOFTWARE LICENSE' "$UVE_TOOLCHAIN/include/GL/glu.h" \
        || { echo "glu.h download looks wrong"; rm -f "$UVE_TOOLCHAIN/include/GL/glu.h"; exit 1; }
fi

# ---------------------------------------------------------------------------------------------
# 7. SwiftShader Vulkan (CPU, Vulkan 1.3) + loader. @sparticuz/chromium ships Chromium's own
#    copies inside the npm tarball as bin/swiftshader.tar.br (brotli) - the only place on the
#    reachable hosts that has a prebuilt Linux Vulkan implementation.
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/vulkan/libvk_swiftshader.so" ]; then
    log "fetch SwiftShader from @sparticuz/chromium@$CHROMIUM_NPM_VERSION (npm, ~70 MB)"
    mkdir -p "$SRC/sparticuz" "$UVE_TOOLCHAIN/vulkan"
    curl -fsSL --retry 3 -o "$SRC/sparticuz/chromium.tgz" \
        "https://registry.npmjs.org/@sparticuz/chromium/-/chromium-$CHROMIUM_NPM_VERSION.tgz"
    tar xzf "$SRC/sparticuz/chromium.tgz" -C "$SRC/sparticuz" package/bin/swiftshader.tar.br
    python3 -c "import brotli,sys; open(sys.argv[2],'wb').write(brotli.decompress(open(sys.argv[1],'rb').read()))" \
        "$SRC/sparticuz/package/bin/swiftshader.tar.br" "$SRC/sparticuz/swiftshader.tar"
    tar xf "$SRC/sparticuz/swiftshader.tar" -C "$UVE_TOOLCHAIN/vulkan" \
        libvk_swiftshader.so libvulkan.so.1 vk_swiftshader_icd.json
    ln -sf libvulkan.so.1 "$UVE_TOOLCHAIN/vulkan/libvulkan.so"
fi

# ---------------------------------------------------------------------------------------------
# 7b. Frame dumper (LD_PRELOAD). The Null platform has no screen to screenshot, so this wraps
#     glfwSwapBuffers() and writes the default framebuffer to PPM - screenshots of the real
#     editor without X11. Source + usage: Engine/Tools/headless_framedump.c.
# ---------------------------------------------------------------------------------------------
if [ ! -f "$UVE_TOOLCHAIN/lib/libuve_framedump.so" ] || [ "$SCRIPT_DIR/headless_framedump.c" -nt "$UVE_TOOLCHAIN/lib/libuve_framedump.so" ]; then
    log "build libuve_framedump.so (LD_PRELOAD screenshot shim)"
    gcc -shared -fPIC -O2 -o "$UVE_TOOLCHAIN/lib/libuve_framedump.so" "$SCRIPT_DIR/headless_framedump.c" -ldl
fi

# ---------------------------------------------------------------------------------------------
# 8. Smoke test: GLFW (Null) -> OSMesa GL 3.3 Core -> glfwGetProcAddress, exactly the engine path.
# ---------------------------------------------------------------------------------------------
log "smoke test"
cat > "$SRC/smoke.c" <<'EOF'
#include <GLFW/glfw3.h>
#include <stdio.h>
int main(void) {
    if (!glfwInit()) { const char* d; glfwGetError(&d); fprintf(stderr, "glfwInit: %s\n", d); return 1; }
    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 3); glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 3);
    glfwWindowHint(GLFW_OPENGL_PROFILE, GLFW_OPENGL_CORE_PROFILE); glfwWindowHint(GLFW_VISIBLE, GLFW_FALSE);
    GLFWwindow* w = glfwCreateWindow(64, 64, "smoke", NULL, NULL);
    if (!w) { const char* d; glfwGetError(&d); fprintf(stderr, "glfwCreateWindow: %s\n", d); return 1; }
    glfwMakeContextCurrent(w);
    const GLubyte* (*getString)(GLenum) = (const GLubyte* (*)(GLenum))glfwGetProcAddress("glGetString");
    printf("OpenGL : %s | %s\n", getString(GL_RENDERER), getString(GL_VERSION));
    glfwDestroyWindow(w); glfwTerminate(); return 0;
}
EOF
gcc "$SRC/smoke.c" -I"$UVE_TOOLCHAIN/include" -L"$UVE_TOOLCHAIN/lib" -lglfw -o "$SRC/smoke" && "$SRC/smoke"
printf 'Vulkan : '
python3 - <<'PY' 2>/dev/null || echo "(pip install vulkan to probe; ICD is at $VK_ICD_FILENAMES)"
from vulkan import *
inst = vkCreateInstance(VkInstanceCreateInfo(pApplicationInfo=VkApplicationInfo(
    pApplicationName='p', applicationVersion=1, pEngineName='p', engineVersion=1, apiVersion=VK_MAKE_VERSION(1, 1, 0))), None)
for d in vkEnumeratePhysicalDevices(inst):
    p = vkGetPhysicalDeviceProperties(d); v = p.apiVersion
    print(f"{p.deviceName} (Vulkan {VK_VERSION_MAJOR(v)}.{VK_VERSION_MINOR(v)})")
PY

if [ "${UVE_KEEP_SRC:-0}" != "1" ]; then
    log "cleanup sources (set UVE_KEEP_SRC=1 to keep)"
    rm -rf "$SRC"
fi
log "done - 'source ~/.univex_env' then configure the engine; UVE_HAS_DESKTOP_GL will be ON:"
log "  cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=Debug -DUVE_BUILD_TESTS=ON \\"
log "        -DCMAKE_PREFIX_PATH=\"$UVE_TOOLCHAIN\" -DOpenGL_GL_PREFERENCE=LEGACY \\"
log "        -DOPENGL_INCLUDE_DIR=\"$UVE_TOOLCHAIN/include\" -DOPENGL_gl_LIBRARY=\"$UVE_TOOLCHAIN/lib/libGL.so\""
