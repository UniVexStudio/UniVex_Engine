"""Single-source UniVex shader validator & cross-compiler (GLSL -> SPIR-V / GLES3 / HLSL / MSL).

Discovers built-in or project `.glsl` shaders, splits combined `#ifdef VERTEX_SHADER` /
`#ifdef FRAGMENT_SHADER` files into per-stage sources, validates preprocessor/brace integrity,
and invokes `glslangValidator` or `glslc` (plus optional `spirv-cross`) when present on PATH.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple


DEFAULT_SHADER_DIR = Path(__file__).resolve().parents[1] / "Runtime" / "RHI" / "Shader" / "built_in"

STAGE_EXTENSIONS = {
    "vert": ".vert",
    "frag": ".frag",
    "comp": ".comp",
}


def detect_stages(source: str) -> List[str]:
    stages: List[str] = []
    if re.search(r"#\s*(?:ifdef|if\s+defined\s*\(?)\s*VERTEX_SHADER\b", source):
        stages.append("vert")
    if re.search(r"#\s*(?:ifdef|if\s+defined\s*\(?)\s*FRAGMENT_SHADER\b", source):
        stages.append("frag")
    if re.search(r"layout\s*\([^)]*local_size_x", source):
        if "comp" not in stages:
            stages.append("comp")
    return stages


def rewrite_for_dialect(source: str, stage: str, target: str) -> str:
    """Rewrites #version and injects stage define for the requested target dialect."""
    lines = source.splitlines(keepends=True)
    body_lines: List[str] = []
    for line in lines:
        if line.lstrip().startswith("#version"):
            continue
        body_lines.append(line)

    stage_define = {
        "vert": "#define VERTEX_SHADER 1\n",
        "frag": "#define FRAGMENT_SHADER 1\n",
        "comp": "#define COMPUTE_SHADER 1\n",
    }[stage]

    if target == "gles3":
        header = "#version 300 es\nprecision highp float;\nprecision highp int;\n"
    elif target == "spirv":
        header = "#version 450\n#define UVE_VULKAN 1\n"
    else:
        header = "#version 430 core\n"

    return header + stage_define + "".join(body_lines)


def validate_glsl_structure(path: Path, source: str) -> List[str]:
    errors: List[str] = []
    stages = detect_stages(source)
    if not stages:
        errors.append(f"{path.name}: no shader stage detected (VERTEX_SHADER, FRAGMENT_SHADER, or local_size_x)")

    depth = 0
    for lineno, raw in enumerate(source.splitlines(), start=1):
        stripped = raw.strip()
        if re.match(r"^#\s*(if|ifdef|ifndef)\b", stripped):
            depth += 1
        elif re.match(r"^#\s*endif\b", stripped):
            depth -= 1
            if depth < 0:
                errors.append(f"{path.name}:{lineno}: unmatched #endif")
                depth = 0
    if depth != 0:
        errors.append(f"{path.name}: unbalanced preprocessor conditionals ({depth} unclosed)")
    return errors


def find_spirv_compiler() -> Tuple[Optional[str], Optional[str]]:
    glslc = shutil.which("glslc")
    if glslc:
        return ("glslc", glslc)
    glslang = shutil.which("glslangValidator")
    if glslang:
        return ("glslangValidator", glslang)
    return (None, None)


def compile_stage_to_spirv(
    compiler_kind: str, compiler_path: str, glsl_text: str, stage: str, out_spv: Path
) -> Tuple[bool, str]:
    stage_src = out_spv.with_suffix(STAGE_EXTENSIONS[stage])
    stage_src.parent.mkdir(parents=True, exist_ok=True)
    stage_src.write_text(glsl_text, encoding="utf-8")

    if compiler_kind == "glslc":
        cmd = [compiler_path, f"-fshader-stage={stage}", str(stage_src), "-o", str(out_spv)]
    else:
        cmd = [compiler_path, "-V", "-S", stage, str(stage_src), "-o", str(out_spv)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        return (False, (proc.stdout + "\n" + proc.stderr).strip())
    return (True, "")


def cross_compile_spirv(spv_path: Path, target: str, out_path: Path) -> Tuple[bool, str]:
    spirv_cross = shutil.which("spirv-cross")
    if not spirv_cross:
        return (False, "spirv-cross not found on PATH")
    flag_map = {
        "gles3": ["--es", "--version", "300"],
        "hlsl": ["--hlsl", "--shader-model", "50"],
        "msl": ["--msl"],
        "glsl": ["--version", "430"],
    }
    cmd = [spirv_cross, str(spv_path), *flag_map[target], "--output", str(out_path)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        return (False, (proc.stdout + "\n" + proc.stderr).strip())
    return (True, "")


def emit_cpp_header(spv_entries: Dict[str, bytes], header_path: Path) -> None:
    lines = [
        "// Copyright (c) 2026 UniVex Studios. All Rights Reserved.",
        "// Auto-generated by Engine/Tools/compile_shaders.py.",
        "#pragma once",
        "#include <cstddef>",
        "namespace UVE::Render::GeneratedSpirv {",
    ]
    for symbol, data in sorted(spv_entries.items()):
        escaped = "".join(f"\\x{b:02x}" for b in data)
        lines.append(f'inline const char k{symbol}SpirvBytes[] = "{escaped}";')
        lines.append(f"inline constexpr std::size_t k{symbol}SpirvSize = {len(data)}U;")
    lines.append("} // namespace UVE::Render::GeneratedSpirv")
    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="UniVex single-source shader validator & cross-compiler")
    parser.add_argument("--input-dir", type=Path, default=DEFAULT_SHADER_DIR)
    parser.add_argument("--out-dir", type=Path, default=None)
    parser.add_argument("--target", choices=["spirv", "gles3", "hlsl", "msl", "glsl"], default="spirv")
    parser.add_argument("--validate-sources", action="store_true", help="Validate shader structure without requiring external compilers")
    parser.add_argument("--manifest", type=Path, default=None)
    parser.add_argument("--emit-header", type=Path, default=None)
    args = parser.parse_args(argv)

    shader_files = sorted(args.input_dir.glob("*.glsl"))
    if not shader_files:
        print(f"No .glsl shaders found in {args.input_dir}", file=sys.stderr)
        return 1

    manifest_entries: List[Dict[str, object]] = []
    all_errors: List[str] = []
    compiler_kind, compiler_path = find_spirv_compiler()
    spv_blobs: Dict[str, bytes] = {}

    for shader_path in shader_files:
        source = shader_path.read_text(encoding="utf-8")
        struct_errors = validate_glsl_structure(shader_path, source)
        all_errors.extend(struct_errors)
        stages = detect_stages(source)
        entry: Dict[str, object] = {
            "name": shader_path.stem,
            "path": shader_path.name,
            "sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
            "stages": stages,
        }
        if not args.validate_sources and args.out_dir is not None and not struct_errors:
            if compiler_kind is None or compiler_path is None:
                all_errors.append("No SPIR-V compiler (glslc or glslangValidator) found on PATH")
                break
            for stage in stages:
                rewritten = rewrite_for_dialect(source, stage, "spirv")
                spv_path = args.out_dir / f"{shader_path.stem}.{stage}.spv"
                ok, err = compile_stage_to_spirv(compiler_kind, compiler_path, rewritten, stage, spv_path)
                if not ok:
                    all_errors.append(f"{shader_path.name} ({stage}): {err}")
                    continue
                spv_blobs[f"{shader_path.stem}_{stage}"] = spv_path.read_bytes()
                if args.target != "spirv":
                    x_out = args.out_dir / f"{shader_path.stem}.{stage}.{args.target}"
                    ok_x, err_x = cross_compile_spirv(spv_path, args.target, x_out)
                    if not ok_x:
                        all_errors.append(f"{shader_path.name} ({stage}->{args.target}): {err_x}")
        manifest_entries.append(entry)

    if args.manifest is not None:
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(json.dumps({"shaders": manifest_entries}, indent=2) + "\n", encoding="utf-8")

    if args.emit_header is not None and spv_blobs:
        emit_cpp_header(spv_blobs, args.emit_header)

    if all_errors:
        for err in all_errors:
            print(f"[compile_shaders] ERROR: {err}", file=sys.stderr)
        return 1

    print(f"[compile_shaders] OK: processed {len(shader_files)} shader(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
