#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <vector>

#include "uve/math/quaternion_uve.h"
#include "uve/math/vector3_uve.h"
#include "uve/physics/detail/collider_world_aabb_cache_uve.h"

namespace UVE::Physics {

/// Trajectory states evaluating physical movement, stability, and flight.
enum class TrajectoryStateUVE : std::uint8_t {
    StableLocomotion = 0,
    BalanceDisturbance,
    CorrectiveStepping,
    UnrecoverableBalanceLoss,
    ForwardFalling,
    BackwardFalling,
    SidewaysFalling,
    AirborneMovement,
    ReboundAfterImpact,
    WallCollisionDuringFlight,
    GroundCollision,
    SecondaryAirborneMovement,
    LandingStabilization,
    Recovery,
};

/// One point along the predicted trajectory.
struct TrajectoryPointUVE final {
    float timeSeconds = 0.0F;
    Math::Vector3UVE position{};
    Math::Vector3UVE linearVelocity{};
    Math::Vector3UVE angularVelocity{};
    Math::Vector3UVE acceleration{};
    Math::QuaternionUVE orientation{};
    Math::Vector3UVE centerOfMass{};

    [[nodiscard]] bool operator==(const TrajectoryPointUVE&) const noexcept = default;
};

/// An obstacle or surface intersection forecasted along the trajectory.
struct PredictedContactEventUVE final {
    float timeSeconds = 0.0F;
    Math::Vector3UVE contactPosition{};
    Math::Vector3UVE contactNormal{0.0F, 1.0F, 0.0F};
    Math::Vector3UVE incomingVelocity{};
    Math::Vector3UVE outgoingVelocity{};
    bool isWall = false;
    bool isGround = false;
    float surfaceSlopeDegrees = 0.0F;

    [[nodiscard]] bool operator==(const PredictedContactEventUVE&) const noexcept = default;
};

/// The full prediction package generated by the Motion Trajectory system.
struct MotionTrajectoryPredictionUVE final {
    TrajectoryStateUVE state = TrajectoryStateUVE::StableLocomotion;

    std::vector<TrajectoryPointUVE> samples;
    std::vector<PredictedContactEventUVE> predictedContacts;

    Math::Vector3UVE currentPosition{};
    Math::Vector3UVE currentVelocity{};
    Math::Vector3UVE currentAngularVelocity{};
    Math::Vector3UVE currentAcceleration{};
    Math::Vector3UVE centerOfMass{};
    Math::QuaternionUVE currentOrientation{};

    bool hasPredictedLanding = false;
    float timeToLanding = 0.0F;
    Math::Vector3UVE predictedLandingPosition{};
    Math::Vector3UVE predictedLandingNormal{0.0F, 1.0F, 0.0F};
    Math::Vector3UVE predictedLandingVelocity{};
    Math::QuaternionUVE predictedLandingOrientation{};
    float landingSlopeDegrees = 0.0F;

    bool hasPredictedWallHit = false;
    float timeToWallHit = 0.0F;
    Math::Vector3UVE predictedWallHitPosition{};
    Math::Vector3UVE predictedWallHitNormal{0.0F, 0.0F, 1.0F};

    float timeHorizonSeconds = 2.0F;
    float timeStepSeconds = 1.0F / 60.0F;
};

/// Input parameters provided to the trajectory forecasting solver.
struct TrajectoryInputUVE final {
    Math::Vector3UVE position{};
    Math::Vector3UVE linearVelocity{};
    Math::Vector3UVE angularVelocity{};
    Math::Vector3UVE acceleration{};
    Math::QuaternionUVE orientation{};
    Math::Vector3UVE centerOfMassOffset{};
    Math::Vector3UVE gravity{0.0F, -9.81F, 0.0F};

    float characterRadius = 0.35F;
    float characterHeight = 1.8F;
    float restitution = 0.15F;
    float friction = 0.6F;
    float linearAirDrag = 0.05F;
    float angularAirDamping = 0.2F;

    bool isGrounded = true;
    bool balanceDisturbed = false;
    Math::Vector3UVE disturbanceImpulse{};

    float horizonSeconds = 2.0F;
    float stepSeconds = 1.0F / 60.0F;
};

/// Evaluates and forecasts the motion trajectory.
[[nodiscard]] MotionTrajectoryPredictionUVE PredictMotionTrajectoryUVE(
    const TrajectoryInputUVE& input,
    std::span<const Detail::ColliderWorldAabbUVE> worldColliders) noexcept;

/// Updates the trajectory state based on new collision or recovery observations.
[[nodiscard]] TrajectoryStateUVE EvaluateTrajectoryStateTransitionUVE(
    TrajectoryStateUVE currentState,
    bool isGrounded,
    float linearSpeed,
    float angularSpeed,
    const Math::Vector3UVE& balanceError,
    float balanceErrorThreshold,
    bool hadWallHit) noexcept;

} // namespace UVE::Physics
