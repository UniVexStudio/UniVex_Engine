namespace UVE::UI::Prism {

/// Shading / pipeline mode for a Prism draw command.
enum class PrismPipelineModeUVE : std::uint8_t {
    SolidOrTextured, // Flat-color or bilinearly sampled RGBA texture
    SdfFont,         // Multi-channel Signed Distance Field glyph rendering with crisp subpixel borders
    DropShadow,      // Analytic analytical gaussian/box blurred shadow quad
};

/// 4 independent corner radii (TopLeft, TopRight, BottomRight, BottomLeft) in clockwise order.
struct PrismCornerRadiiUVE final {
    float topLeft = 0.0F;
    float topRight = 0.0F;
    float bottomRight = 0.0F;
    float bottomLeft = 0.0F;

    constexpr PrismCornerRadiiUVE() noexcept = default;
    constexpr explicit PrismCornerRadiiUVE(float uniformRadius) noexcept
        : topLeft(uniformRadius), topRight(uniformRadius), bottomRight(uniformRadius), bottomLeft(uniformRadius) {}
    constexpr PrismCornerRadiiUVE(float tl, float tr, float br, float bl) noexcept
        : topLeft(tl), topRight(tr), bottomRight(br), bottomLeft(bl) {}

    [[nodiscard]] constexpr bool IsZero() const noexcept {
        return topLeft <= 0.0F && topRight <= 0.0F && bottomRight <= 0.0F && bottomLeft <= 0.0F;
    }

    [[nodiscard]] constexpr bool operator==(const PrismCornerRadiiUVE&) const noexcept = default;
};

/// Linear RGBA color for the Prism UI vector engine and styling.
struct PrismColorUVE final {
    float r = 0.0F;
    float g = 0.0F;
    float b = 0.0F;
    float a = 1.0F;

    constexpr PrismColorUVE() noexcept = default;
    constexpr PrismColorUVE(float r_, float g_, float b_, float a_ = 1.0F) noexcept
        : r(r_), g(g_), b(b_), a(a_) {}
    constexpr PrismColorUVE(Math::ColorUVE rgb, float a_ = 1.0F) noexcept
        : r(rgb.r), g(rgb.g), b(rgb.b), a(a_) {}

    [[nodiscard]] constexpr Math::ColorUVE ToRGB() const noexcept {
        return Math::ColorUVE{r, g, b};
    }

    [[nodiscard]] constexpr bool operator==(const PrismColorUVE&) const noexcept = default;
};

/// Single 2D vertex generated by the Prism geometry engine.
/// Exactly 32 bytes: cache-line aligned and SIMD friendly.
struct PrismVertexUVE final {
    Math::Vector2UVE position{0.0F, 0.0F};
    Math::Vector2UVE uv{0.0F, 0.0F};
    PrismColorUVE   color{1.0F, 1.0F, 1.0F, 1.0F}; // Linear RGBA float

    [[nodiscard]] constexpr bool operator==(const PrismVertexUVE&) const noexcept = default;
};

/// A single batched draw call with clipping and texture binding.
struct PrismDrawCmdUVE final {
    std::uint32_t       indexOffset = 0;
    std::uint32_t       indexCount = 0;
    Math::RectIntUVE    clipRect{}; // Screen-space scissor rect: (minX, minY, maxX, maxY)
    std::uint64_t       textureId = 0; // Backend texture handle or atlas ID
    PrismPipelineModeUVE pipeline = PrismPipelineModeUVE::SolidOrTextured;

    [[nodiscard]] constexpr bool operator==(const PrismDrawCmdUVE&) const noexcept = default;
};

} // namespace UVE::UI::Prism
